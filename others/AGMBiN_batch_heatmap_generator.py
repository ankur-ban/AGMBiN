def save_AGMBiN_heatmap(model, image_path, output_path, device):
    """Generates the attention overlay for a single image and saves it directly to disk."""
    model.eval()

    # Load and resize original image
    original_pil = Image.open(image_path).convert('RGB')
    original_resized = original_pil.resize((224, 224))
    original_np = np.array(original_resized)

    normalize = transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    transform = transforms.Compose([transforms.Resize((224, 224)), transforms.ToTensor(), normalize])
    input_tensor = transform(original_pil).unsqueeze(0).to(device)

    # Attach forward hook to the Attention Gate
    attention_map = None
    def hook_fn(module, input, output):
        nonlocal attention_map
        attention_map = output.detach().cpu()

    base_model = model._orig_mod if hasattr(model, '_orig_mod') else model
    hook_handle = base_model.attn_pool.register_forward_hook(hook_fn)

    # Forward pass
    with torch.no_grad():
        with torch.amp.autocast('cuda'):
            model(input_tensor)

    hook_handle.remove()

    # Process heatmap
    heatmap = attention_map.float().mean(dim=1).squeeze().numpy()
    heatmap = np.maximum(heatmap, 0)
    heatmap = (heatmap - np.min(heatmap)) / (np.max(heatmap) - np.min(heatmap) + 1e-8)

    heatmap_resized = cv2.resize(heatmap, (224, 224))
    heatmap_colored = cv2.applyColorMap(np.uint8(255 * heatmap_resized), cv2.COLORMAP_JET)
    heatmap_colored = cv2.cvtColor(heatmap_colored, cv2.COLOR_BGR2RGB)

    # Create overlay
    overlay = cv2.addWeighted(original_np, 0.6, heatmap_colored, 0.4, 0)

    # Convert from RGB back to BGR for OpenCV saving
    overlay_bgr = cv2.cvtColor(overlay, cv2.COLOR_RGB2BGR)
    cv2.imwrite(output_path, overlay_bgr)


def heatmaps_batch_process(source_dir, heatmap_dir, model, device, suffix):
    """Iterates through a folder of images and saves the heatmaps using the provided model."""
    os.makedirs(heatmap_dir, exist_ok=True)

    valid_extensions = ('.png', '.jpg', '.jpeg', '.bmp')
    image_files = [f for f in os.listdir(source_dir) if f.lower().endswith(valid_extensions)]

    print(f"Processing {len(image_files)} images from '{source_dir}' -> '{heatmap_dir}'")

    for file_name in tqdm(image_files, desc=f"Generating {suffix} Heatmaps"):
        image_path = os.path.join(source_dir, file_name)

        name_without_ext = os.path.splitext(file_name)[0]
        output_file_name = f"{name_without_ext}_{suffix}.jpg"
        output_path = os.path.join(heatmap_dir, output_file_name)

        save_AGMBiN_heatmap(model, image_path, output_path, device)


