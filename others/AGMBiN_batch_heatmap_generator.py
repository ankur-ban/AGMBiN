def load_robust_checkpoint(model, checkpoint_path, device):
    """Loads a checkpoint, handles dictionary wrappers, and filters shape mismatches."""
    ckpt = torch.load(checkpoint_path, map_location=device)

    # 1. Extract the actual weights (handles standard checkpoints vs raw weights)
    state_dict = ckpt.get('state_dict', ckpt.get('model', ckpt))

    # 2. Filter out keys with shape mismatches (e.g., the 1000-class vs 200-class fc layer)
    model_state = model.state_dict()
    filtered_state_dict = {
        k: v for k, v in state_dict.items()
        if k in model_state and v.shape == model_state[k].shape
    }

    # 3. Load the filtered weights
    model.load_state_dict(filtered_state_dict, strict=False)
    return model

